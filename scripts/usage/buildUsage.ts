/**
 * Counts sign value usage from the glossaries in Oracc project JSON zips, and
 * writes one file per language to data/usage/:
 *
 *   npm run build-usage -- epsd2.zip akklove.zip …
 *
 * Prints a summary in Markdown for the update's pull request. Glossaries that
 * Oracc has cut short are skipped and listed in the summary. scripts/updateUsage.sh downloads the zips and runs
 * this. See docs/usage-data.md.
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, writeFileSync } from "node:fs"
import { posix } from "node:path"

import {
  filesInZip,
  glossaryEntries,
  glossaryInstances,
} from "./readGlossary.ts"
import {
  formsOf,
  LANGUAGES,
  UsageCount,
  type Form,
  type GlossaryKind,
} from "./usageCount.ts"

/** A glossary file in a zip. */
interface Glossary {
  zip: string
  file: string
  kind: GlossaryKind
  project: string
}

const GLOSSARY = /(^|\/)gloss-(sux|akk|qpn)(-[^/]*)?\.json$/

const OUTPUT = new URL("../../data/usage/", import.meta.url)

const zips = process.argv.slice(2)
const glossaries = zips.flatMap(glossariesIn)
const count = new UsageCount()
const projects = new Map<GlossaryKind, Set<string>>()
const skipped: string[] = []

// Names count under the language of their text, so they go last.
const languagesFirst = [
  ...glossaries.filter((g) => g.kind !== "qpn"),
  ...glossaries.filter((g) => g.kind === "qpn"),
]
for (const glossary of languagesFirst) {
  const name = `${glossary.project}/${posix.basename(glossary.file)}`
  if (isComplete(glossary)) {
    console.error(name)
    await countGlossary(glossary)
    projects.set(
      glossary.kind,
      (projects.get(glossary.kind) ?? new Set()).add(glossary.project),
    )
  } else {
    skipped.push(name)
    console.error(`${name}: skipped, cut short`)
  }
}

mkdirSync(OUTPUT, { recursive: true })
console.log("| Language | Values | Uses | Projects |")
console.log("| -------- | -----: | ---: | -------: |")
for (const language of LANGUAGES) {
  const values = count.usage(language)
  const used = projects.get(language) ?? new Set()
  const file = {
    comment:
      "Generated by npm run build-usage from Oracc's glossaries, released under CC0. Don't edit by hand.",
    language,
    projects: [...used].sort(),
    values,
  }
  writeFileSync(new URL(`${language}.json`, OUTPUT), JSON.stringify(file))

  const uses = Object.values(values).reduce((sum, v) => sum + v.n, 0)
  const row = [language, Object.keys(values).length, uses, used.size]
  console.log(`| ${row.join(" | ")} |`)
}
if (skipped.length > 0) {
  console.log("\nSkipped, because Oracc's file is cut short:\n")
  for (const name of skipped) console.log(`- \`${name}\``)
}

function glossariesIn(zip: string): Glossary[] {
  return filesInZip(zip).flatMap((file) => {
    const kind = GLOSSARY.exec(file)?.[2] as GlossaryKind | undefined
    return kind ? [{ zip, file, kind, project: posix.dirname(file) }] : []
  })
}

/**
 * Whether a glossary file ends where its JSON does. Some of Oracc's are cut
 * short, and counting one part way would count only some of its words.
 */
function isComplete({ zip, file }: Glossary): boolean {
  const unzip = spawnSync(
    "sh",
    ["-c", 'unzip -p "$0" "$1" | tail -c 16', zip, file],
    {
      encoding: "utf8",
    },
  )
  return unzip.stdout.trimEnd().endsWith("}")
}

/** Counts every use of every spelling in a glossary. */
async function countGlossary({ zip, file, kind }: Glossary): Promise<void> {
  const forms = new Map<string, Form>()
  for await (const entry of glossaryEntries(zip, file)) {
    for (const [xis, form] of formsOf(entry)) forms.set(xis, form)
  }
  for await (const [xis, refs] of glossaryInstances(zip, file)) {
    const form = forms.get(xis)
    if (form) count.add(kind, form, refs)
  }
}
